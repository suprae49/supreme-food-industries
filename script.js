/* Live calculator via backend (C++/C/Python); sale price is separate from CSR. */
const OFFLINE_PRICE_PER_KG_NPR = 110;
let calcRequest = 0;

function renderCalc(data) {
  document.querySelector("#calc-kg").textContent = String(Math.round(data.total_kg));
  document.querySelector("#calc-q").textContent = Number(data.total_quintal).toFixed(3);
  document.querySelector("#calc-rate").textContent = Number(data.price_per_kg_npr).toLocaleString("en-IN");
  document.querySelector("#calc-total").textContent = Number(data.total_price_npr).toLocaleString("en-IN");
  document.querySelector("#calc-csr").textContent = String(data.csr_fund_npr);
  document.querySelector("#calc-engine").textContent = `engine: ${data.lang || "python"}`;
}

async function refreshCalc() {
  const requestId = ++calcRequest;
  const bags = Math.min(5000, Math.max(1, Math.trunc(Number(bagsInput?.value) || 1)));
  const totalKg = bags * 25;
  // Update immediately; an older response must not overwrite newer input.
  renderCalc({
    total_kg: totalKg,
    total_quintal: totalKg / 100,
    price_per_kg_npr: OFFLINE_PRICE_PER_KG_NPR,
    total_price_npr: totalKg * OFFLINE_PRICE_PER_KG_NPR,
    csr_fund_npr: totalKg,
    lang: "offline",
  });
  try {
    const res = await fetch(`/api/calc?bags=${bags}&kg=25`, { cache: "no-store" });
    const data = await res.json();
    if (!res.ok || !data.ok ||
        ![data.total_kg, data.total_quintal, data.price_per_kg_npr,
          data.total_price_npr, data.csr_fund_npr].every(Number.isFinite)) {
      throw new Error("Calculator unavailable");
    }
    if (requestId === calcRequest) renderCalc(data);
  } catch {
    // The local estimate remains visible; order saving still requires the server.
  }
}

bagsInput?.addEventListener("input", refreshCalc);
refreshCalc();

orderForm?.addEventListener("submit", async (event) => {
  event.preventDefault();
  const data = new FormData(orderForm);
  const btn = orderForm.querySelector('button[type="submit"]');
  btn.disabled = true;
  orderNote.hidden = true;
  try {
    const result = await api("/api/order", {
      method: "POST",
      body: JSON.stringify({
        name: data.get("name"),
        phone: data.get("phone"),
        variety: data.get("variety"),
        bags: Number(data.get("bags")),
        note: data.get("note"),
      }),
    });
    orderNote.hidden = false;
    orderNote.textContent = result.ok ? result.message : result.error;
    orderNote.classList.toggle("is-error", !result.ok);
    if (result.ok) {
      orderForm.reset();
      bagsInput.value = "2";
      refreshCalc();
      prefill(orderForm);
    }
  } catch {
    orderNote.hidden = false;
    orderNote.textContent = "सर्भरसँग जोडिन सकिएन।";
    orderNote.classList.add("is-error");
  } finally {
    btn.disabled = false;
  }
});

