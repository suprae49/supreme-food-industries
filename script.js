const session = typeof getSession === "function" ? getSession() : null;
function prefill(form) {
  if (!session || !form) return;
  const nameInput = form.querySelector('input[name="name"]');
  const phoneInput = form.querySelector('input[name="phone"]');
  if (nameInput && !nameInput.value) nameInput.value = session.name || "";
  if (phoneInput && !phoneInput.value) phoneInput.value = session.phone || "";
}
prefill(contactForm);
prefill(orderForm);

function applyLang() {
  const dict = I18N[lang] || I18N.ne;
  document.documentElement.lang = lang;
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    if (dict[key]) el.textContent = dict[key];
  });
  if (langToggle) langToggle.textContent = lang === "ne" ? "EN" : "ने";
  localStorage.setItem("sfi_lang", lang);
}

langToggle?.addEventListener("click", () => {
  lang = lang === "ne" ? "en" : "ne";
  applyLang();
});
applyLang();

